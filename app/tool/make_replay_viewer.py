#!/usr/bin/env python3
"""Builds the conversation viewer pages from one source (docs/design/share-codes.md).

Sources (site/share/): viewer.js, viewer.css, viewer.html (the page skeleton).

Outputs:
  app/lib/share_code/replay_viewer.g.dart
      The self-contained page the app's 「导出为网页」 fills in: script and style
      inlined, `__DSHGO_TITLE__` / `__DSHGO_DATA__` left for the app, no network
      (`connect-src 'none'`).
  <out>/ (default site/build/share, or --out DIR)
      What the share host publishes: c.html (the hosted viewer, the same page
      with `connect-src 'self'`, served for /c/<id>), and the landing page
      (index.html, share.js, viewer.js, viewer.css, icons) as is.

The inline script is pinned by a CSP hash, so a page can't run anything else.

  python3 app/tool/make_replay_viewer.py            # write both
  python3 app/tool/make_replay_viewer.py --check    # fail if the .g.dart is stale
"""

import argparse
import base64
import hashlib
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / 'site' / 'share'
DART = ROOT / 'app' / 'lib' / 'share_code' / 'replay_viewer.g.dart'
LANDING = ['index.html', 'share.js', 'viewer.js', 'viewer.css', 'favicon.svg', 'apple-touch-icon.png']


def sources():
    return {name: (SITE / name).read_text(encoding='utf-8') for name in ('viewer.js', 'viewer.css', 'viewer.html')}


def source_hash(src):
    h = hashlib.sha256()
    for name in ('viewer.js', 'viewer.css', 'viewer.html'):
        h.update(name.encode())
        h.update(b'\0')
        h.update(src[name].encode('utf-8'))
        h.update(b'\0')
    return h.hexdigest()


def page(src, *, connect, title, data):
    script = src['viewer.js'].rstrip() + '\nDshgoViewer.boot();\n'
    for bad in ('</script', '<!--'):
        if bad in script.lower() or bad in src['viewer.css'].lower():
            sys.exit(f'viewer source contains {bad!r}: it would end the inline block')
    digest = base64.b64encode(hashlib.sha256(script.encode('utf-8')).digest()).decode()
    out = src['viewer.html']
    for key, value in (
        ('{{SCRIPT_HASH}}', f'sha256-{digest}'),
        ('{{CONNECT}}', connect),
        ('{{TITLE}}', title),
        ('{{CSS}}', src['viewer.css'].strip()),
        ('{{DATA}}', data),
        ('{{JS}}', script),
    ):
        if key not in out:
            sys.exit(f'viewer.html lacks {key}')
        out = out.replace(key, value, 1)
    return out


def dart(src):
    export = page(src, connect="'none'", title='__DSHGO_TITLE__', data='__DSHGO_DATA__')
    if "'''" in export:
        sys.exit("viewer source contains ''' (can't go into a Dart raw string)")
    return (
        '// GENERATED by app/tool/make_replay_viewer.py from site/share/viewer.{js,css,html}.\n'
        '// Do not edit: change the sources and run the tool again.\n'
        '// ignore_for_file: lines_longer_than_80_chars\n\n'
        '/// The self-contained conversation page 「导出为网页」 fills in\n'
        '/// (`__DSHGO_TITLE__`, `__DSHGO_DATA__`; see conversation_html.dart).\n'
        f"const replayViewerPage = r'''{export}''';\n\n"
        '/// What the page was built from (test/share_code/replay_viewer_sync_test.dart).\n'
        f"const replayViewerSourceHash = '{source_hash(src)}';\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--out', type=Path, default=ROOT / 'site' / 'build' / 'share')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    src = sources()
    generated = dart(src)
    if args.check:
        current = DART.read_text(encoding='utf-8') if DART.exists() else ''
        if current != generated:
            sys.exit(f'{DART.relative_to(ROOT)} is stale: run app/tool/make_replay_viewer.py')
        print('up to date')
        return
    DART.write_text(generated, encoding='utf-8')
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    (out / 'c.html').write_text(page(src, connect="'self'", title='dsh-go 对话', data=''), encoding='utf-8')
    for name in LANDING:
        shutil.copyfile(SITE / name, out / name)
    print(f'wrote {DART.relative_to(ROOT)} and {out}')


if __name__ == '__main__':
    main()
