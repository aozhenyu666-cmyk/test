package com.yishou.app.llm

/**
 * 六骰子：六种可以调用的思考动作。编号和职责固定，六面并列，不是 1 到 6 的顺序流程。
 * 掷骰只是选择入口，不是训练成果。
 */
data class Face(
    val number: Int,
    /** 界面上用的短名 */
    val short: String,
    val name: String,
    /** 我的最小动作 */
    val action: String,
    /** 陪练怎样检查 */
    val check: String,
    /** 标准句式：先照着说，熟了再丢掉 */
    val frame: String,
)

object Faces {
    val ALL = listOf(
        Face(1, "精简", "精简、总结、记忆", "用自己的话说清一条核心关系，留下一个调用关键词", "是否忠于材料、保留必要条件；需要时让他讲给初学者听", "核心是____，因为____；关键词：____"),
        Face(2, "预判", "预判", "在结果出现前说一个预期及主要依据", "对比预期与实际；结果还没出现就标为待验证", "我预计____，依据是____"),
        Face(3, "联想", "联想", "找一个旧知识或情境，说明具体联系", "联系能否帮助理解或行动，哪里不能照搬", "这像____，相同在____，不同在____"),
        Face(4, "提问", "提问", "提出一个影响当前判断的具体问题", "问题是否指向真实缺口，需要什么信息才能回答", "我还不确定____，要先弄清____"),
        Face(5, "体系", "知识体系构建", "用两三个概念及明确关系给新知识定位", "关系是否成立；不把词语堆积当成体系", "____属于____，它和____的关系是____"),
        Face(6, "回响", "回响", "先回忆旧内容，再用于当前问题或对照资料", "记住什么、遗漏什么、能否重新使用；没有记录不假装记得", "我记得____，用到这里就是____"),
    )

    fun of(n: Int): Face? = ALL.firstOrNull { it.number == n }

    /** 写进系统提示词的六面表 */
    fun table(): String = ALL.joinToString("\n") {
        "${it.number} ${it.name}：最小动作——${it.action}；检查——${it.check}；标准句式——${it.frame}"
    }
}
