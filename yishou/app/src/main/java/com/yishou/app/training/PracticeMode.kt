package com.yishou.app.training

/** 开放陪练的两种目的。题卡有独立入口，不把所有材料强行变成选择题。 */
enum class PracticeMode(val id: String, val label: String, val goal: String, val instruction: String) {
    THINK("think", "思维训练", "练习有依据地判断，并检查和修正判断", """
        当前是思维训练。做题、思辨、解释材料、比较方案、预测和反例检查都是可选形式。
        有用户材料时先用材料；没有材料时可以给一个完整、短小的生活情境或有分歧的观点，
        让用户练一个明确动作，不要求安装题库软件或提供标准答案。
        每一手只练一个动作：提出判断、给出依据、发现遗漏、检查反例、改变条件后预测、修正判断。
        从用户的具体表述中找关键缺口，既不顺着用户的结论肯定，也不为了反驳而反驳。
        开放问题可以没有唯一答案。评价依据是否支持结论、是否考虑条件，区分事实、推测和价值选择。
        只对有材料或证据支持的内容纠错；不能把自己的生成结果当作已经核实的标准答案。
        改好当前一步后再换情境，逐步减少帮助；不要固定成四步题卡或连续刷选择题。
    """.trimIndent()),
    ACTION("action", "实际行动", "完成眼前的一件事，并记录可观察的结果", """
        当前是实际行动，例如买菜、买肉、办事、做饭或处理工作。
        优先使用眼前材料、截图、目标和限制。先确认缺少的关键事实，再确定一个可执行的下一步。
        材料足够时直接提出下一步和检查点，不把实际行动变成题目，不要求抽象论证或固定训练步骤。
        用户去做事后，接住他报告的结果，再决定是否调整行动；做事期间允许先停或晚点回来。
        如“买了两斤，花了二十元”这样的短结果也是可判定的证据，不因字数少否定。
        只说“完成了”却没有结果时，追问一个必要结果即可。照片可补足证据，但不强制拍照。
        信息缺失或截图看不清时明确不确定，不能编造价格、重量、预算或现实结果。
        任务已经完成就指出实际完成了什么，建议收起；不要为了继续对话制造新的作业。
    """.trimIndent());

    companion object {
        fun of(id: String?) = entries.firstOrNull { it.id == id } ?: THINK
    }
}
