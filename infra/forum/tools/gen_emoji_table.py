#!/usr/bin/env python3
"""Generates app/lib/forum/emoji_data.g.dart from Discourse's emoji database.

The forum client renders posts from Discourse's cooked HTML, where an emoji is
an <img class="emoji" alt=":name:">. The app shows the system emoji instead
(text, not a picture), so it needs name -> code points for every name and
alias Discourse knows.

Usage (from the repository root, network needed once):

    python3 infra/forum/tools/gen_emoji_table.py

Source: https://github.com/discourse/discourse-emojis (dist/emojis.json and
dist/aliases.json; MIT).
"""

import json
import pathlib
import urllib.request

BASE = "https://raw.githubusercontent.com/discourse/discourse-emojis/main/dist/"
OUT = pathlib.Path(__file__).resolve().parents[3] / "app/lib/forum/emoji_data.g.dart"


def fetch(name):
    with urllib.request.urlopen(BASE + name, timeout=60) as response:
        return json.load(response)


def main():
    emojis = fetch("emojis.json")
    aliases = fetch("aliases.json")
    table = {e["name"]: e["code"] for e in emojis if e.get("name") and e.get("code")}
    for name, extra in aliases.items():
        code = table.get(name)
        if code is None:
            continue
        for alias in extra:
            table.setdefault(alias, code)
    for name in table:
        if any(c in name for c in ";:\n"):
            raise SystemExit(f"unexpected character in emoji name {name!r}")
    entries = ";".join(f"{name}:{code}" for name, code in sorted(table.items()))
    lines = [entries[i : i + 100] for i in range(0, len(entries), 100)]
    body = "\n".join(f"  '{line}'" for line in lines)
    OUT.write_text(
        "// GENERATED by infra/forum/tools/gen_emoji_table.py from Discourse's emoji\n"
        "// database (github.com/discourse/discourse-emojis, MIT). Do not edit.\n"
        "//\n"
        "// `name:codepoints` pairs separated by `;`, code points in hex joined by `-`.\n"
        "\n"
        "// dart format off\n"
        f"const emojiData =\n{body};\n",
        encoding="utf-8",
    )
    print(f"{len(table)} names -> {OUT}")


if __name__ == "__main__":
    main()
